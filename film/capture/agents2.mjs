import { chromium } from 'playwright'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 2 })
await ctx.addInitScript(() => { localStorage.setItem('atlas.projet', '67900866-5415-4cf4-9262-4cd1cd16e06c'); localStorage.setItem('atlas.vue', 'agents') })
const pg = await ctx.newPage()
await pg.goto('http://localhost:5173/')
await pg.waitForTimeout(5000)
await pg.click('.sessions-liste a[data-id="14029774-3a45-495a-b83d-4fb6e6d2c2c5"]')
await pg.waitForTimeout(7000)
await pg.mouse.click(1865, 518)
await pg.waitForTimeout(2500)
await pg.mouse.move(1900, 1060)
await pg.screenshot({ path: 'capture/ui/session-agents-deplie.png' })
await b.close()
